async def mount(page, initial=None, js=JS):
 html=re.sub(r'<meta http-equiv="Content-Security-Policy"[^>]*>','',HTML).replace('<link rel="stylesheet" href="styles.css">','').replace('<script src="app.js" defer></script>','')
 await page.set_content(html)
 await page.evaluate('''([key,value])=>{const store={};if(value!==null)store[key]=value;window.__store=store;Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem(k){return window.__store[k]??null},setItem(k,v){window.__store[k]=String(v)},removeItem(k){delete window.__store[k]}}});}''',[KEY,initial])
 await page.add_style_tag(content=CSS)
