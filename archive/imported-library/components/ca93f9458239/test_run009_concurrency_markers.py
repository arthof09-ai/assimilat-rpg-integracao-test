async def raw(page):return await page.evaluate(f'window.__store[{json.dumps(KEY)}]||null')
async def sc(page):return await page.evaluate('window.__tabletopTEST.scene()')
async def transfer(source,target,send_event=True):
 data=await raw(source)
 await target.evaluate('([k,v,event])=>{window.__store[k]=v;if(event)window.dispatchEvent(new StorageEvent("storage",{key:k,newValue:v}));}',[KEY,data,send_event])
 return data
